import numpy as np  # noqa: E402
from food import banana_models as BM, carrot_models as CM, roll_models as RM  # noqa: E402

rng = np.random.default_rng(7)
N = 200
ok_r = 0
for _ in range(N):
    age = float(rng.choice([0.5, 2.0, 6.0, 20.0, 30.0, 48.0, 96.0])) * float(np.exp(rng.normal(0, 0.2)))
    st = str(rng.choice(["paper_bag", "plastic_bag", "open"]))
    crisp, E = float(RM.crispness(RM.crust_water(age, st))), float(RM.crumb_E_kPa(age))
    b = RM.RollBelief(np.random.default_rng(int(rng.integers(1 << 30))), n=1500)
    b.observe_stiffness(0.29 * E / 20.0 * float(np.exp(rng.normal(0, 0.15))))
    b.observe_crackles(int(rng.poisson(0.3 + 12 * crisp)))
    pc = b.p_class()
    ok_r += max(pc, key=pc.get) == RM.freshness_class(crisp, E)
err_b = []
for _ in range(N):
    s_true = float(rng.uniform(1, 7))
    b = BM.BananaBelief(np.random.default_rng(int(rng.integers(1 << 30))), n=1500)
    b.observe_hue(BM.peel_hue(s_true) + float(rng.normal(0, 3)))
    err_b.append(b.summary()["stage_mean"] - s_true)
ok_c = 0
for _ in range(N):
    age, st = float(rng.uniform(1, 21)), str(rng.choice(list(CM.LOSS_RATE)))
    limp = 1 - CM.LOSS_RATE[st] * age / 100 / 0.88 < 0.95
    b = CM.CarrotBelief(np.random.default_rng(int(rng.integers(1 << 30))), n=1500)
    b.observe_bend(limp if rng.random() > 0.05 else not limp)
    ok_c += (b.summary()["p_limp"] > 0.5) == limp
BEL = (f"freshness class {100 * ok_r / N:.0f} % (squeeze k + crackles, {N} rolls)",
       f"stage RMS error {float(np.sqrt(np.mean(np.square(err_b)))):.2f} (one hue reading, {N} fingers)",
       f"limp class {100 * ok_c / N:.0f} % (one bend test, {N} roots)")
